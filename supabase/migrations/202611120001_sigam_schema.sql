-- API requests set the Supabase Auth subject before switching to `authenticated`.
CREATE OR REPLACE FUNCTION public.sigam_user_id()
RETURNS BIGINT LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT id FROM users WHERE auth_user_id = auth.uid() AND active = 1 LIMIT 1 $$;

CREATE OR REPLACE FUNCTION public.sigam_user_role()
RETURNS TEXT LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT role FROM users WHERE auth_user_id = auth.uid() AND active = 1 LIMIT 1 $$;

CREATE OR REPLACE FUNCTION public.sigam_department_id()
RETURNS BIGINT LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT department_id FROM user_units WHERE user_id = public.sigam_user_id() LIMIT 1 $$;

CREATE OR REPLACE FUNCTION public.sigam_sector_id()
RETURNS BIGINT LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT sector_id FROM user_units WHERE user_id = public.sigam_user_id() LIMIT 1 $$;

CREATE OR REPLACE FUNCTION public.sigam_api_request()
RETURNS BOOLEAN LANGUAGE sql STABLE
AS $$ SELECT current_setting('sigam.backend', true) = '1' $$;

GRANT EXECUTE ON FUNCTION public.sigam_user_id() TO authenticated;
GRANT EXECUTE ON FUNCTION public.sigam_user_role() TO authenticated;
GRANT EXECUTE ON FUNCTION public.sigam_department_id() TO authenticated;
GRANT EXECUTE ON FUNCTION public.sigam_sector_id() TO authenticated;
GRANT EXECUTE ON FUNCTION public.sigam_api_request() TO authenticated;

