-- Private object storage. Objects are addressed as <SIGAM user ID>/<stored filename>.
INSERT INTO storage.buckets (id, name, public, file_size_limit)
VALUES ('sigam-documentos', 'sigam-documentos', FALSE, 8388608)
ON CONFLICT (id) DO UPDATE SET public = FALSE, file_size_limit = 8388608;
CREATE POLICY sigam_document_owner_read ON storage.objects FOR SELECT TO authenticated
  USING (bucket_id = 'sigam-documentos' AND (storage.foldername(name))[1] = public.sigam_user_id()::text);
CREATE POLICY sigam_document_owner_insert ON storage.objects FOR INSERT TO authenticated
  WITH CHECK (bucket_id = 'sigam-documentos' AND (storage.foldername(name))[1] = public.sigam_user_id()::text);
CREATE POLICY sigam_document_owner_delete ON storage.objects FOR DELETE TO authenticated
  USING (bucket_id = 'sigam-documentos' AND (storage.foldername(name))[1] = public.sigam_user_id()::text);

